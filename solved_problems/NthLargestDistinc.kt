/**
 * Задача: поиск N-го самого большого числа в массиве
 * 
 * Дан массив из M целых чисел. Требуется найти N-е по величине число,
 * при этом равные числа считаются одним и тем же числом. Если ответа
 * не существует — вывести -1.
 * 
 * Формат входных данных:
 *   Первая строка: M и N — количество чисел в массиве и искомый номер.
 *   Вторая строка: M целых чисел, разделённых пробелами.
 * 
 * Формат выходных данных:
 *   Одно число — N-е по величине или -1, если ответа не существует.
 * 
 * Пример: M = 6, N = 3, массив [1, 2, 3, -9, 3, 5] → 2.
 */

// Время: O(M log M), Память: O(M)
fun solve(numbers: List<Int>, n: Int): Int {
    val uniqueSortedNumbers = numbers.toSet().sortedDescending()
    return uniqueSortedNumbers.getOrElse(n - 1) { -1 } 
}

fun main() {
   val (_, n) = readln().split(" ").map { it.toInt() }
   val numbers = readln().split(" ").map { it.toInt() }
   println(solve(numbers, n))
}